// ========================================
// LANGUAGE MANAGEMENT
// ========================================
let currentLang = localStorage.getItem('language') || 'en';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('language', lang);
    
    // Update all translated elements
    document.querySelectorAll('[data-translate]').forEach(el => {
        const key = el.getAttribute('data-translate');
        if (translations[lang] && translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });
    
    // Update active language button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
    });
    document.querySelector(`.lang-btn[onclick*="${lang}"]`)?.classList.add('active');
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
}

// ========================================
// INITIALIZATION
// ========================================
document.addEventListener('DOMContentLoaded', () => {
    // Apply saved language
    setLanguage(currentLang);
    
    // Loading screen
    setTimeout(() => {
        document.getElementById('loadingScreen').style.opacity = '0';
        setTimeout(() => {
            document.getElementById('loadingScreen').style.display = 'none';
        }, 300);
    }, 500);
    
    // Mobile menu toggle
    const mobileToggle = document.getElementById('mobileToggle');
    const navMenu = document.getElementById('navMenu');
    
    mobileToggle?.addEventListener('click', () => {
        mobileToggle.classList.toggle('active');
        navMenu.classList.toggle('active');
    });
    
    // Close mobile menu on link click
    document.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', () => {
            mobileToggle?.classList.remove('active');
            navMenu?.classList.remove('active');
        });
    });
    
    // Smooth scroll
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                target.scrollIntoView({ behavior: 'smooth', block: 'start' });
            }
        });
    });
    
    // Navbar scroll behavior
    let lastScroll = 0;
    const navbar = document.getElementById('navbar');
    
    window.addEventListener('scroll', () => {
        const currentScroll = window.pageYOffset;
        
        if (currentScroll > 100) {
            navbar.classList.add('scrolled');
            
            if (currentScroll > lastScroll) {
                navbar.style.transform = 'translateY(-100%)';
            } else {
                navbar.style.transform = 'translateY(0)';
            }
        } else {
            navbar.classList.remove('scrolled');
        }
        
        lastScroll = currentScroll;
    });
    
    // Counter animation
    const animateCounter = (el) => {
        const target = parseInt(el.getAttribute('data-count'));
        const duration = 2000;
        const increment = target / (duration / 16);
        let current = 0;
        
        const updateCounter = () => {
            current += increment;
            if (current < target) {
                el.textContent = Math.floor(current) + (el.textContent.includes('+') ? '+' : '');
                requestAnimationFrame(updateCounter);
            } else {
                el.textContent = target + (el.textContent.includes('+') ? '+' : '');
            }
        };
        
        updateCounter();
    };
    
    // Intersection Observer for counters
    const counterObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting && !entry.target.classList.contains('animated')) {
                animateCounter(entry.target);
                entry.target.classList.add('animated');
            }
        });
    }, { threshold: 0.5 });
    
    document.querySelectorAll('.stat-num').forEach(counter => {
        counterObserver.observe(counter);
    });
    
    // Form submission
    const form = document.getElementById('contactForm');
    form?.addEventListener('submit', async (e) => {
        e.preventDefault();
        
        const formData = new FormData(form);
        const button = form.querySelector('button[type="submit"]');
        const message = document.getElementById('formMessage');
        
        button.disabled = true;
        button.textContent = currentLang === 'en' ? 'Sending...' : currentLang === 'pt-br' ? 'Enviando...' : 'A enviar...';
        
        try {
            const response = await fetch('https://api.web3forms.com/submit', {
                method: 'POST',
                body: formData
            });
            
            if (response.ok) {
                message.textContent = currentLang === 'en' ? 'Message sent successfully!' : currentLang === 'pt-br' ? 'Mensagem enviada com sucesso!' : 'Mensagem enviada com sucesso!';
                message.className = 'form-message success';
                form.reset();
            } else {
                throw new Error('Failed');
            }
        } catch (error) {
            message.textContent = currentLang === 'en' ? 'Failed to send message. Please try email directly.' : currentLang === 'pt-br' ? 'Falha ao enviar. Por favor, use o email diretamente.' : 'Falha ao enviar. Por favor, use o email diretamente.';
            message.className = 'form-message error';
        }
        
        button.disabled = false;
        button.innerHTML = `<span data-translate="form_submit">${translations[currentLang].form_submit}</span><svg width="20" height="20" viewBox="0 0 20 20"><path d="M4 10H16M16 10L11 5M16 10L11 15" stroke="currentColor" stroke-width="2" stroke-linecap="round"/></svg>`;
    });
});
